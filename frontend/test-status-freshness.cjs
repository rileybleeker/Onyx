const fs = require('node:fs');
const vm = require('node:vm');
const assert = require('node:assert/strict');
const ts = require('typescript');
const source = fs.readFileSync('src/lib/status-freshness.ts', 'utf8');
const output = ts.transpileModule(source, { compilerOptions: { module: ts.ModuleKind.CommonJS } }).outputText;
const sandbox = { exports: {} };
vm.runInNewContext(output, sandbox);
const status = sandbox.exports.ingestionHeartbeatStatus;
const now = Date.parse('2026-11-11T05:00:00Z');
const row = (hours, state = 'success') => ({ sync_start: new Date(now - hours * 3_600_000).toISOString(), status: state });
assert.equal(status('success', row(200), 3, 6, now), 'failed', 'frozen spine cannot hide outage');
assert.equal(status('success', row(3), 3, 6, now), 'success');
assert.equal(status('success', row(3.001), 3, 6, now), 'partial');
assert.equal(status('success', row(6), 3, 6, now), 'partial');
assert.equal(status('success', row(6.001), 3, 6, now), 'failed');
assert.equal(status('success', row(24), 26, 30, now), 'success', 'daily importer overnight gap');
assert.equal(status('success', row(27), 26, 30, now), 'partial');
assert.equal(status('success', row(31), 26, 30, now), 'failed');
for (const state of ['failed', 'error']) assert.equal(status('success', row(0, state), 3, 6, now), 'failed');
assert.equal(status('partial', row(0), 3, 6, now), 'partial');
assert.equal(status('failed', row(0), 3, 6, now), 'failed');
for (const entry of [null, { sync_start: 'bad' }, row(-1), row(0, 'running')]) assert.equal(status('success', entry, 3, 6, now), 'unknown');
assert.equal(status('success', row(0), 3, 6, now), 'success', 'zero-row successful runs remain valid');
console.log('PASS: 17 ingestion heartbeat freshness and boundary checks');
